import { describe, expect, it } from "vitest";

import { parsePlanAmountInput, serializePlanAmount } from "./planAmounts";

describe("plan amount input", () => {
    it.each([
        ["", null],
        ["   ", null],
        ["0", 0],
        ["0.00", 0],
        ["700", 70000],
        ["1034.89", 103489],
        ["1034,89", 103489],
        [" 700,5 ", 70050],
        ["0.01", 1],
        ["9999999999.99", 999999999999],
        ["\u00a0\u202f", null],
        ["7157", 715700],
        ["7 157", 715700],
        ["7157.02", 715702],
        ["7157,02", 715702],
        ["7 157,02 €", 715702],
        ["7 157.02", 715702],
        ["7.157,02", 715702],
        ["7,157.02", 715702],
        ["€7,157.02", 715702],
        ["EUR 7 157,02", 715702],
        ["7 157,02 eur", 715702],
        ["eUr 7157,02", 715702],
        ["\u00a07\u00a0157,02\u00a0€\u00a0", 715702],
        ["\u202f7\u202f157,02\u202f€\u202f", 715702],
        ["1,034.89", 103489],
        ["1.034,89", 103489],
        ["1 034,89", 103489],
        ["€700", 70000],
        ["0,00 €", 0],
        ["€0.00", 0],
        ["1 234,5", 123450],
        ["1,234.5", 123450],
        ["€0,01", 1],
        ["12 345 678", 1234567800],
        ["9 999 999 999,99 €", 999999999999],
        ["9.999.999.999,99", 999999999999],
        ["€9,999,999,999.99", 999999999999],
    ])("parses %s into %s cents", (input, cents) => {
        expect(parsePlanAmountInput(input)).toBe(cents);
    });

    it.each([
        "-0.01",
        "1.001",
        "1.230",
        "10000000000.00",
        "bad",
        "NaN",
        "Infinity",
        "1e2",
        "1.234",
        "1,234",
        "7,157",
        "12 34,56",
        "1234 567,89",
        "1 23 456,78",
        "1,23.45",
        "1.23,45",
        "1 234,567.89",
        "1.234 567,89",
        "1,,234.56",
        "1..234,56",
        "1 234,",
        "1 234.5678",
        "7 157,023 €",
        "€-700",
        "-700 €",
        "(700,00 €)",
        "€700€",
        "EUR €700",
        "700 EUR EUR",
        "€",
        " EUR ",
        "7€157,02",
        "$700",
        "USD 700",
        "700 euros",
        "700 EUR extra",
        "€1e2",
        "10 000 000 000,00 €",
        "€10,000,000,000.00",
    ])("rejects invalid input %s", (input) => {
        expect(() => parsePlanAmountInput(input)).toThrow();
    });
});

describe("pasted plan amount serialization", () => {
    it.each([
        ["7 157,02 €", "7157.02"],
        ["7.157,02", "7157.02"],
        ["€7,157.02", "7157.02"],
        ["1 234,5", "1234.50"],
        ["0,00 €", "0.00"],
        ["\u00a0\u202f", null],
        ["9 999 999 999,99 €", "9999999999.99"],
    ])("serializes pasted %s as canonical %s", (input, amount) => {
        expect(serializePlanAmount(parsePlanAmountInput(input))).toBe(amount);
    });
});

describe("plan amount serialization", () => {
    it.each([
        [null, null],
        [0, "0.00"],
        [1, "0.01"],
        [10, "0.10"],
        [103489, "1034.89"],
        [70000, "700.00"],
        [999999999999, "9999999999.99"],
    ])("serializes %s cents as %s", (cents, amount) => {
        expect(serializePlanAmount(cents)).toBe(amount);
    });
});
